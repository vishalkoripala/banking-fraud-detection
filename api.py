"""
api.py

Real-time fraud scoring API.

Endpoints
---------
GET  /health       liveness/readiness check
GET  /model/info   deployed model's identity + honest held-out test metrics
POST /predict       score one transaction, with a SHAP-based explanation

Run locally:
    uvicorn api:app --host 0.0.0.0 --port 8000

Interactive docs (auto-generated by FastAPI from the Pydantic schema below)
are then at http://localhost:8000/docs
"""
import json
import logging
import os
import time
from contextlib import asynccontextmanager
from typing import Literal

import joblib
import pandas as pd
import sklearn
from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import JSONResponse, HTMLResponse
from pydantic import BaseModel, Field, create_model

from explain import FraudExplainer
from demo import DEMO_HTML

MODEL_PATH = "model/fraud_model.joblib"
METADATA_PATH = "model/model_metadata.json"
BACKGROUND_PATH = "model/background_sample.csv"

# ---------------------------------------------------------------------------
# Logging: every prediction is logged as one JSON line. This dataset's V1-V28
# are already PCA-anonymized (no raw PII), so logging full feature vectors is
# safe here. If you point this API at a schema with real PII (raw card/account
# fields), redact or hash those fields before they reach this logger.
# ---------------------------------------------------------------------------
logger = logging.getLogger("fraud_api")
logger.setLevel(logging.INFO)
os.makedirs("logs", exist_ok=True)
_handler = logging.FileHandler("logs/predictions.log")
_handler.setFormatter(logging.Formatter("%(message)s"))
logger.addHandler(_handler)
logger.addHandler(logging.StreamHandler())

# ---------------------------------------------------------------------------
# App state populated at startup (avoids reloading the model per request)
# ---------------------------------------------------------------------------
state: dict = {}


@asynccontextmanager
async def lifespan(app: FastAPI):
    with open(METADATA_PATH) as f:
        state["metadata"] = json.load(f)

    # scikit-learn does not guarantee pickle compatibility across versions --
    # a model fit with one version can fail with a confusing AttributeError
    # (not a clear "version mismatch" message) when loaded under another.
    # Catch that here, at startup, with an actionable message instead of
    # letting the first /predict request surface a cryptic 500 error.
    trained_version = state["metadata"].get("sklearn_version")
    running_version = sklearn.__version__
    if trained_version and trained_version != running_version:
        print(
            f"WARNING: model/fraud_model.joblib was trained with "
            f"scikit-learn {trained_version}, but scikit-learn "
            f"{running_version} is installed. This MAY cause prediction "
            f"errors (e.g. 'object has no attribute ...'). If /predict "
            f"fails, delete model/ and rerun train_final_model.py to "
            f"rebuild the model with your installed version, or "
            f"`pip install -r requirements.txt` to match the pinned, "
            f"tested versions exactly."
        )

    state["pipeline"] = joblib.load(MODEL_PATH)
    background = pd.read_csv(BACKGROUND_PATH)
    state["explainer"] = FraudExplainer(state["pipeline"], background_X=background)
    state["feature_order"] = state["metadata"]["feature_order"]
    print(f"Loaded model '{state['metadata']['model_name']}' "
          f"(trained {state['metadata']['trained_at_utc']}), "
          f"threshold={state['metadata']['decision_threshold']:.6f}")
    yield
    state.clear()


app = FastAPI(
    title="Banking Fraud Detection API",
    description="Real-time credit card fraud scoring with SHAP-based explanations.",
    version="1.0.0",
    lifespan=lifespan,
)


@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception):
    # Never leak internals (stack traces, file paths) to a client in production.
    logger.error(json.dumps({"event": "unhandled_error", "path": str(request.url), "error": str(exc)}))
    return JSONResponse(status_code=500, content={"detail": "Internal error while scoring transaction."})


# ---------------------------------------------------------------------------
# Request/response schemas
# ---------------------------------------------------------------------------
_pca_fields = {f"V{i}": (float, Field(..., description=f"PCA component {i}")) for i in range(1, 29)}
Transaction: type[BaseModel] = create_model(
    "Transaction",
    Time=(float, Field(..., description="Seconds elapsed since the first transaction in the dataset", ge=0)),
    Amount=(float, Field(..., description="Transaction amount", ge=0)),
    **_pca_fields,
)


class TopFactor(BaseModel):
    feature: str
    value: float
    contribution: float
    direction: Literal["increases_risk", "decreases_risk"]


class PredictionResponse(BaseModel):
    fraud_probability: float
    flagged: bool
    threshold_used: float
    top_factors: list[TopFactor]
    model_name: str
    scoring_time_ms: float


# ---------------------------------------------------------------------------
# Endpoints
# ---------------------------------------------------------------------------
@app.get("/", response_class=HTMLResponse, include_in_schema=False)
def demo_page():
    return DEMO_HTML


@app.get("/health")
def health():
    return {"status": "ok", "model_loaded": "pipeline" in state}


@app.get("/model/info")
def model_info():
    return state["metadata"]


@app.post("/predict", response_model=PredictionResponse)
def predict(transaction: Transaction):
    t0 = time.perf_counter()

    row = pd.DataFrame([transaction.model_dump()])[state["feature_order"]]

    try:
        proba = float(state["pipeline"].predict_proba(row)[0, 1])
        top_factors = state["explainer"].explain_instance(row, top_n=5)
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Scoring failed: {exc}") from exc

    threshold = state["metadata"]["decision_threshold"]
    flagged = proba >= threshold
    elapsed_ms = (time.perf_counter() - t0) * 1000

    response = PredictionResponse(
        fraud_probability=round(proba, 6),
        flagged=flagged,
        threshold_used=threshold,
        top_factors=top_factors,
        model_name=state["metadata"]["model_name"],
        scoring_time_ms=round(elapsed_ms, 2),
    )

    logger.info(json.dumps({
        "event": "prediction",
        "fraud_probability": response.fraud_probability,
        "flagged": response.flagged,
        "scoring_time_ms": response.scoring_time_ms,
    }))

    return response
